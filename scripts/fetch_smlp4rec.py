"""Download the SMLP4Rec model class from the authors' repo and adapt it for Expedia.

The authors' repository (Applied-Machine-Learning-Lab/SMLP4Rec, Gao et al., TOIS 2024) carries no
license, so `smlprec.py` is not redistributed here. This script fetches it and applies the small
changes this project needs, writing `src/nbp/models/smlprec.py` (gitignored).

Changes, each marked "# ADAPTED":
- sequence length comes from config['MAX_ITEM_LIST_LENGTH'] instead of a hard-coded 50;
- an empty `selected_features` list is allowed (hotel clusters have no item attributes): the
  item-feature layer is skipped and the mixer runs on item embeddings only.

Usage: python scripts/fetch_smlp4rec.py
"""

import urllib.request
from pathlib import Path

URL = "https://raw.githubusercontent.com/Applied-Machine-Learning-Lab/SMLP4Rec/main/smlprec.py"
OUT = Path(__file__).resolve().parents[1] / "src" / "nbp" / "models" / "smlprec.py"

HEADER = '''"""SMLP4Rec (Gao et al., TOIS 2024), fetched from github.com/Applied-Machine-Learning-Lab/SMLP4Rec.

Generated by scripts/fetch_smlp4rec.py; not part of this repository's license. Adaptations are
marked "# ADAPTED".
"""
'''

# (old, new) pairs applied to the upstream source, each must match exactly once
PATCHES = [
    (
        "    def __init__(self, config, dataset, seq_len = 50):\n"
        "        super(SMLPREC, self).__init__(config, dataset)\n",
        "    def __init__(self, config, dataset, seq_len = None):\n"
        "        super(SMLPREC, self).__init__(config, dataset)\n"
        "        seq_len = seq_len or config['MAX_ITEM_LIST_LENGTH']  # ADAPTED\n",
    ),
    (
        "        self.selected_features = config['selected_features']\n",
        "        self.selected_features = config['selected_features'] or []  # ADAPTED\n",
    ),
    (
        "        self.num_feature_field = len(config['selected_features'])\n",
        "        self.num_feature_field = len(self.selected_features)  # ADAPTED\n",
    ),
    (
        "        self.feature_embed_layer = FeatureSeqEmbLayer(\n"
        "            dataset, self.hidden_size, self.selected_features, self.pooling_mode, self.device\n"
        "        )\n",
        "        self.feature_embed_layer = None  # ADAPTED: no item features -> no feature layer\n"
        "        if self.num_feature_field > 0:\n"
        "            self.feature_embed_layer = FeatureSeqEmbLayer(\n"
        "                dataset, self.hidden_size, self.selected_features, self.pooling_mode, self.device\n"
        "            )\n",
    ),
    (
        "        sparse_embedding, dense_embedding = self.feature_embed_layer(None, item_seq)\n"
        "        sparse_embedding = sparse_embedding['item']\n"
        "        dense_embedding = dense_embedding['item']\n"
        "\n"
        "        if sparse_embedding is not None:\n"
        "            feature_embeddings = sparse_embedding\n"
        "        if dense_embedding is not None:\n",
        "        item_emb = torch.unsqueeze(item_emb,2)\n"
        "        if self.feature_embed_layer is not None:  # ADAPTED\n"
        "            sparse_embedding, dense_embedding = self.feature_embed_layer(None, item_seq)\n"
        "            sparse_embedding = sparse_embedding['item']\n"
        "            dense_embedding = dense_embedding['item']\n"
        "\n"
        "            if sparse_embedding is not None:\n"
        "                feature_embeddings = sparse_embedding\n"
        "            if dense_embedding is not None:\n",
    ),
    (
        "            if sparse_embedding is not None:\n"
        "                feature_embeddings = torch.cat((sparse_embedding,dense_embedding),2)\n"
        "            else:\n"
        "                feature_embeddings = dense_embedding\n",
        "                if sparse_embedding is not None:\n"
        "                    feature_embeddings = torch.cat((sparse_embedding,dense_embedding),2)\n"
        "                else:\n"
        "                    feature_embeddings = dense_embedding\n",
    ),
    (
        "        item_emb = torch.unsqueeze(item_emb,2)\n"
        "        item_emb = torch.cat((item_emb,feature_embeddings),2)\n",
        "            item_emb = torch.cat((item_emb,feature_embeddings),2)\n",
    ),
]


def main() -> None:
    src = urllib.request.urlopen(URL, timeout=30).read().decode("utf-8").replace("\r\n", "\n")
    for old, new in PATCHES:
        if src.count(old) != 1:
            raise SystemExit(f"upstream smlprec.py changed, patch does not apply:\n{old}")
        src = src.replace(old, new)
    OUT.write_text(HEADER + src, encoding="utf-8")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
